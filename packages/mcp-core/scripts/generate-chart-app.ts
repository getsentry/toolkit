/**
 * Bundles the chart view (chart-app/) into one self-contained
 * HTML document and writes it to src/ui/chart-app.generated.ts, so the stdio
 * server and the Cloudflare Worker serve it without reading files.
 *
 * `--check` fails instead of writing when the committed file is stale. Both
 * modes fail when the view breaks a rule in view-policy.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";
import { CHART_UI_RESOURCE } from "../src/ui-resources.ts";
import { viewHtmlProblems } from "./view-policy.ts";

const BUDGET_BYTES = CHART_UI_RESOURCE.budgetBytes;

const appDir = fileURLToPath(new URL("../chart-app/", import.meta.url));
const outFile = fileURLToPath(
  new URL("../src/ui/chart-app.generated.ts", import.meta.url),
);

const bundle = await build({
  entryPoints: [`${appDir}main.ts`],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  legalComments: "none",
  charset: "utf8",
  write: false,
});
const script = bundle.outputFiles[0]?.text;
if (!script) {
  throw new Error("esbuild produced no output for chart-app/main.ts");
}
const style = await transform(readFileSync(`${appDir}styles.css`, "utf8"), {
  loader: "css",
  minify: true,
});

const html = [
  "<!doctype html>",
  '<html lang="en"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  "<title>Sentry chart</title>",
  `<style>${style.code.trim()}</style></head>`,
  // An inline script ends at the first `</script`, wherever it appears.
  `<body><script>${script.trim().replaceAll("</script", "<\\/script")}</script></body></html>`,
].join("");

const problems = viewHtmlProblems("The chart view", html, BUDGET_BYTES);
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const source = `// Generated by scripts/generate-chart-app.ts from chart-app/. Do not edit.
export const CHART_APP_HTML = ${JSON.stringify(html)};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outFile, "utf8") !== source) {
    console.error(
      "src/ui/chart-app.generated.ts is stale. Run: pnpm --filter @sentry/mcp-core generate-chart-app",
    );
    process.exit(1);
  }
  console.log("src/ui/chart-app.generated.ts is up to date.");
} else {
  writeFileSync(outFile, source);
  console.log(
    `Wrote src/ui/chart-app.generated.ts (${Buffer.byteLength(html)} of ${BUDGET_BYTES} bytes).`,
  );
}
