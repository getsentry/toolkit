/**
 * What a command may do (permission class) and where agents may run it
 * (exposure). `sentry mcp` lists and runs commands by these fields: its
 * command tools carry hints from the permission class, which hosts allowlist
 * by (#1254). `check:command-access` keeps them honest.
 */

/**
 * Where agents may run a command:
 * - `exposed`: on stdio and hosted MCP.
 * - `stdio-only`: needs the user's machine (local files, the `cwd`, git,
 *   the local credential store, or a terminal).
 * - `hidden`: never offered to agents (session management, CLI
 *   maintenance, `local`, `monitor run`).
 */
export type CommandExposure = "exposed" | "stdio-only" | "hidden";

/** Accepted {@link CommandExposure} values. */
export const COMMAND_EXPOSURES: readonly CommandExposure[] = [
  "exposed",
  "stdio-only",
  "hidden",
];

/**
 * What a command may do to Sentry: `read` sends only GET, HEAD, or OPTIONS;
 * `write` sends anything else; `destructive` is any command built with
 * `destructive: true` or `buildDeleteCommand`.
 */
type PermissionClass = "read" | "write" | "destructive";

/**
 * A command's {@link PermissionClass}, or `method` when each call takes the
 * class of the HTTP method it sends (`sentry api --method`).
 */
export type CommandPermission = PermissionClass | "method";

/**
 * A permission a command declares itself. Most commands declare none: their
 * class comes from the Sentry API requests they send. `check:command-access`
 * asks for a declaration only where those requests can't settle it.
 */
export type DeclaredPermission = Exclude<CommandPermission, "destructive">;

/**
 * Class of the Sentry API requests a command sends, generated by
 * `generate:command-api`. `unknown`: a request whose method the source
 * analysis can't read. Commands that send no API request have none.
 */
export type ApiAccess = "read" | "write" | "unknown";

const READ_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);
const WRITE_METHODS = new Set(["POST", "PUT", "PATCH", "DELETE"]);

/** Whether `method` is an HTTP method that changes state. */
export function isWriteMethod(method: string): boolean {
  return WRITE_METHODS.has(method);
}

/**
 * Class of a command's Sentry API requests, given their methods
 * (`undefined` for a request whose method is unknown).
 */
export function apiAccess(
  methods: readonly (string | undefined)[],
): ApiAccess | undefined {
  if (methods.some((method) => method !== undefined && isWriteMethod(method)))
    return "write";
  if (
    methods.some((method) => method === undefined || !READ_METHODS.has(method))
  )
    return "unknown";
  return methods.length > 0 ? "read" : undefined;
}

/**
 * A command's permission: `destructive` when flagged, else its declaration,
 * else the class of its API requests. A command without API requests reads;
 * an unknown request counts as a write until the command declares a class.
 */
export function commandPermission(command: {
  destructive?: boolean;
  declared?: DeclaredPermission;
  api?: ApiAccess;
}): CommandPermission {
  if (command.destructive) return "destructive";
  if (command.declared) return command.declared;
  return command.api === undefined || command.api === "read" ? "read" : "write";
}
