/**
 * Generate Shell-Completion Target Sets
 *
 * The `sentry __complete` fast path (src/lib/complete.ts) skips the Stricli
 * boot, so it cannot walk the route tree at runtime to decide which commands
 * complete which arguments, and it must not load the modules that define
 * the values it offers. This script walks the route tree at build time and
 * writes, per command, the completion kind of each positional and
 * value-taking flag as JSON, the subcommands of every route group, and the
 * values completers offer (`COMPLETION_VALUES`). Kinds
 * come from the parsers the arguments already use
 * (src/lib/completion-target.ts); flags without one are still listed so
 * `__complete` can skip their values.
 *
 * The output is gitignored and regenerated by `generate:docs`, which runs as
 * part of `dev`, `build`, `bundle`, `typecheck`, and `test`.
 *
 * Usage:   tsx script/generate.ts completions
 * Output:  src/generated/completion-targets.json
 */

import { mkdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { routes } from "../src/app.js";
import { getApiCompletionPaths } from "../src/lib/api-schema.js";
import { COMPLETION_VALUES } from "../src/lib/completion-target.js";
import {
  extractCommandCompletions,
  extractRouteGroups,
  type RouteMap,
} from "../src/lib/introspect.js";

const OUTPUT_PATH = "src/generated/completion-targets.json";

/** Write the completion kinds, route groups, and completer values. */
export async function emit(): Promise<void> {
  const routeMap = routes as unknown as RouteMap;
  const commands = extractCommandCompletions(routeMap);
  const groups = extractRouteGroups(routeMap);

  // Plain JSON (like api-schema.json) so the output is produced by a real
  // serializer rather than hand-assembled source text.
  mkdirSync("src/generated", { recursive: true });
  await writeFile(
    OUTPUT_PATH,
    `${JSON.stringify({ commands, groups, values: { ...COMPLETION_VALUES, apiPaths: getApiCompletionPaths() } }, null, 2)}\n`,
    "utf8",
  );
  process.stdout.write(
    `Wrote ${OUTPUT_PATH} (${Object.keys(commands).length} commands)\n`,
  );
}
