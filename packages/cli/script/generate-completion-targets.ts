#!/usr/bin/env tsx
/**
 * Generate Shell-Completion Target Sets
 *
 * The `sentry __complete` fast path (src/lib/complete.ts) skips the Stricli
 * boot, so it cannot walk the route tree at runtime to decide which commands
 * complete which arguments, and it must not load the modules that define
 * the values it offers. This script walks the route tree at build time and
 * writes, per command, the completion kind of each positional and
 * value-taking flag as JSON, plus those values (`COMPLETION_VALUES`). Kinds
 * come from the parsers the arguments already use
 * (src/lib/completion-target.ts); flags without one are still listed so
 * `__complete` can skip their values.
 *
 * The output is gitignored and regenerated by `generate:docs`, which runs as
 * part of `dev`, `build`, `bundle`, `typecheck`, and `test`.
 *
 * Usage:   tsx script/generate-completion-targets.ts
 * Output:  src/generated/completion-targets.json
 */

import { mkdirSync } from "node:fs";
import { access, writeFile } from "node:fs/promises";

// Bootstrap: skill-content stub (same pattern as generate-command-docs.ts).
// The route tree transitively imports skill-content.ts, which may not exist
// yet on a fresh checkout. Must run before the dynamic import below.
const SKILL_CONTENT_PATH = "src/generated/skill-content.ts";
const SKILL_CONTENT_STUB =
  "export const SKILL_FILES: [string, string][] = [];\n";
const skillContentExists = await access(SKILL_CONTENT_PATH).then(
  () => true,
  () => false,
);
if (!skillContentExists) {
  mkdirSync("src/generated", { recursive: true });
  await writeFile(SKILL_CONTENT_PATH, SKILL_CONTENT_STUB);
}

import type { RouteMap } from "../src/lib/introspect.js";

const { routes } = await import("../src/app.js");
const { extractCommandCompletions } = await import("../src/lib/introspect.js");
const { COMPLETION_VALUES } = await import("../src/lib/completion-target.js");

const OUTPUT_PATH = "src/generated/completion-targets.json";

const commands = extractCommandCompletions(routes as unknown as RouteMap);

// Plain JSON (like api-schema.json) so the output is produced by a real
// serializer rather than hand-assembled source text.
mkdirSync("src/generated", { recursive: true });
await writeFile(
  OUTPUT_PATH,
  `${JSON.stringify({ commands, values: COMPLETION_VALUES }, null, 2)}\n`,
  "utf8",
);
process.stdout.write(
  `Wrote ${OUTPUT_PATH} (${Object.keys(commands).length} commands)\n`,
);
