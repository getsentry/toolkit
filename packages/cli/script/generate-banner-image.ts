#!/usr/bin/env tsx
/**
 * Generate the Graphics Banner
 *
 * Bakes the Sentry arch + SENTRY wordmark into a PNG that graphics-capable
 * terminals render as a real image, matching the brand gradient of the
 * block-art fallback in `src/lib/banner.ts`.
 *
 * The source is a white-on-transparent alpha mask (`assets/banner-mask.png`);
 * this script applies the vertical brand gradient per row and emits a
 * TRANSPARENT PNG (unpainted pixels are fully transparent, so the banner floats
 * on the terminal background just like the block-art banner — no opaque
 * rectangle). Kitty terminals get the PNG as is; sixel terminals get it
 * encoded at runtime by `src/lib/sixel-image.ts`.
 *
 * Output is a committed module (like `src/generated/skill-content.ts`) so the
 * runtime never needs to read the asset from disk.
 *
 * Usage:   tsx script/generate-banner-image.ts
 * Output:  src/generated/banner-image.ts
 */

import { mkdirSync, readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, "..");
const MASK_PATH = join(REPO_ROOT, "assets", "banner-mask.png");
const OUT_PATH = join(REPO_ROOT, "src", "generated", "banner-image.ts");

/**
 * Vertical brand gradient anchors (top → bottom), matching `BANNER_GRADIENT`
 * in `src/lib/banner.ts`: #9E86FF (top), #7553FF (middle), #583FC1 (bottom).
 */
const GRADIENT_ANCHORS: [number, number, number][] = [
  [0x9e, 0x86, 0xff],
  [0x75, 0x53, 0xff],
  [0x58, 0x3f, 0xc1],
];

/** Number of quantized gradient bands (palette entries). Keeps the image's
 *  sixel encoding small while staying visually smooth across the wordmark
 *  height. */
const COLOR_BANDS = 24;

/** Alpha (0–255) at or above which a mask pixel is painted; below is left
 *  transparent. A hard threshold keeps letterform edges crisp and the palette
 *  tiny (partial-alpha edges can't be blended without knowing the terminal bg). */
const ALPHA_THRESHOLD = 110;

/** Linearly interpolate the brand gradient at t ∈ [0,1] → [r,g,b] (0–255). */
function gradientAt(t: number): [number, number, number] {
  const clamped = Math.min(1, Math.max(0, t));
  const seg = clamped * (GRADIENT_ANCHORS.length - 1);
  const i = Math.min(GRADIENT_ANCHORS.length - 2, Math.floor(seg));
  const f = seg - i;
  const a = GRADIENT_ANCHORS[i] as [number, number, number];
  const b = GRADIENT_ANCHORS[i + 1] as [number, number, number];
  return [
    Math.round(a[0] + (b[0] - a[0]) * f),
    Math.round(a[1] + (b[1] - a[1]) * f),
    Math.round(a[2] + (b[2] - a[2]) * f),
  ];
}

/** A painted-pixel test plus a row→color-band mapping over one image. */
type MaskModel = {
  width: number;
  height: number;
  /** True when pixel (x,y) should be drawn (alpha ≥ threshold). */
  isPainted: (x: number, y: number) => boolean;
  /** Palette index for the given row (vertical gradient). */
  bandForRow: (y: number) => number;
};

/** Build the mask model: painted pixels plus the row → gradient band map. */
function maskModel(png: PNG): MaskModel {
  const { width, height, data } = png;
  return {
    width,
    height,
    isPainted: (x, y) =>
      (data[(y * width + x) * 4 + 3] ?? 0) >= ALPHA_THRESHOLD,
    bandForRow: (y) =>
      Math.min(
        COLOR_BANDS - 1,
        Math.floor((y / Math.max(1, height - 1)) * COLOR_BANDS),
      ),
  };
}

/** The quantized brand gradient, one color per band. */
function gradientPalette(): [number, number, number][] {
  const palette: [number, number, number][] = [];
  for (let n = 0; n < COLOR_BANDS; n++) {
    palette.push(gradientAt((n + 0.5) / COLOR_BANDS));
  }
  return palette;
}

/** Encode the mask as a base64 PNG painted with the quantized gradient. */
function encodePngBase64(mask: PNG): string {
  const palette = gradientPalette();
  const model = maskModel(mask);
  const out = new PNG({ width: mask.width, height: mask.height });
  for (let y = 0; y < mask.height; y++) {
    const [r, g, b] = palette[model.bandForRow(y)] as [number, number, number];
    for (let x = 0; x < mask.width; x++) {
      const i = (y * mask.width + x) * 4;
      out.data[i] = r;
      out.data[i + 1] = g;
      out.data[i + 2] = b;
      out.data[i + 3] = model.isPainted(x, y) ? 255 : 0;
    }
  }
  return PNG.sync.write(out, { deflateLevel: 9 }).toString("base64");
}

async function main(): Promise<void> {
  const png = PNG.sync.read(readFileSync(MASK_PATH));
  const pngBase64 = encodePngBase64(png);

  // generate:banner runs first in the pipeline, so on a fresh checkout it may
  // be the first writer into the (gitignored) src/generated directory.
  mkdirSync(dirname(OUT_PATH), { recursive: true });

  const module = `// AUTO-GENERATED by script/generate-banner-image.ts — DO NOT EDIT.
// Regenerate with: pnpm run generate:banner
/**
 * Baked transparent banner (Sentry arch + SENTRY wordmark, brand gradient).
 * Printed by the CLI on terminals that advertise kitty graphics or sixel
 * support (sixel is encoded from this PNG at runtime); everything else falls
 * back to the block-art banner in src/lib/banner.ts.
 */
export const BANNER_IMAGE = {
  /** Base64 PNG, sent as is with the kitty graphics protocol. */
  png: ${JSON.stringify(pngBase64)},
  /** Rendered image size in device pixels. */
  width: ${png.width},
  height: ${png.height},
} as const;
`;

  await writeFile(OUT_PATH, module, "utf8");
  process.stdout.write(
    `Wrote ${OUT_PATH} (${png.width}x${png.height}, png ${pngBase64.length} base64 bytes)\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`generate-banner-image failed: ${String(err)}\n`);
  process.exit(1);
});
