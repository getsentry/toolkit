/**
 * Generate Output Schema Fields
 *
 * Command output schemas (`src/output-schemas/`) are valibot schemas the CLI
 * only needs for their field list: `--help`, `sentry help <cmd>`, `--fields`
 * parsing and completion, the skill references, and the SDK's return types.
 * Reading that list out of a schema needs the schema, valibot, and
 * everything the schema spreads in from `@sentry/api/valibot`, so this
 * script reads it at build time instead. It loads each module in
 * `src/output-schemas/`, and for each exported valibot schema whose name
 * ends in `Schema` writes its fields and field paths
 * ({@link OutputSchemaFields}) to `src/generated/output-schemas/`, in a
 * module of the same name and under the same export name. Commands import
 * those, so a run loads the field data of its own route's commands and no
 * schema.
 *
 * `src/output-schemas/` must not import from `src/generated/output-schemas/`:
 * this script loads it to write that directory.
 *
 * The output is gitignored and regenerated by `generate:docs`, which runs as
 * part of `dev`, `build`, `bundle`, `typecheck`, and `test`.
 *
 * Usage:   tsx script/generate.ts output-schemas
 * Output:  src/generated/output-schemas/*.ts
 */

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { GenericSchema } from "valibot";
import type { OutputSchemaFields } from "../src/lib/formatters/output.js";
import {
  extractSchemaFieldPaths,
  extractSchemaFields,
} from "./lib/output-schema-fields.js";
import { logger } from "../src/lib/logger.js";

const SOURCE_DIR = "src/output-schemas";
const OUTPUT_DIR = "src/generated/output-schemas";

/** Whether `value` is a valibot schema (not an action or a plain value). */
function isSchema(value: unknown): value is GenericSchema {
  return (
    typeof value === "object" &&
    value !== null &&
    (value as { kind?: unknown }).kind === "schema"
  );
}

/** The generated module for one `src/output-schemas/` module. */
function renderModule(
  name: string,
  schemas: [string, GenericSchema][],
): string {
  const source = `../../output-schemas/${name}.js`;
  const lines = [
    `// Generated by script/generate-output-schemas.ts from ${SOURCE_DIR}/${name}.ts.`,
    "// Do not edit; change the schemas there instead.",
    "",
    'import type { OutputSchemaFields } from "../../lib/formatters/output.js";',
    "import type {",
    ...schemas.map(([exportName]) => `  ${exportName} as ${exportName}Source,`),
    `} from ${JSON.stringify(source)};`,
  ];
  for (const [exportName, schema] of schemas) {
    const fields: OutputSchemaFields = {
      fields: extractSchemaFields(schema),
      paths: extractSchemaFieldPaths(schema),
    };
    lines.push(
      "",
      `export const ${exportName}: OutputSchemaFields<typeof ${exportName}Source> = ${JSON.stringify(fields)};`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/** Write the field data of every output schema. */
export async function emit(): Promise<void> {
  const files = (await readdir(SOURCE_DIR))
    .filter((file) => file.endsWith(".ts"))
    .sort();

  await rm(OUTPUT_DIR, { recursive: true, force: true });
  await mkdir(OUTPUT_DIR, { recursive: true });

  let count = 0;
  for (const file of files) {
    const name = basename(file, ".ts");
    const exports: Record<string, unknown> = await import(
      pathToFileURL(resolve(SOURCE_DIR, file)).href
    );
    const schemas = Object.entries(exports).filter(
      (entry): entry is [string, GenericSchema] =>
        entry[0].endsWith("Schema") && isSchema(entry[1]),
    );
    if (schemas.length === 0) {
      continue;
    }
    count += schemas.length;
    await writeFile(`${OUTPUT_DIR}/${name}.ts`, renderModule(name, schemas));
  }

  logger.success(`Generated ${OUTPUT_DIR}/ (${count} output schemas)`);
}
