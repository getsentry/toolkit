#!/usr/bin/env tsx
/**
 * Compile the shared PEG grammars into committed ES module parsers.
 *
 * toolkit-core ships TypeScript source with no build step, so the CLI, the
 * stdio MCP server, and the Cloudflare worker all import the generated
 * parsers straight from `src/generated/`. `pnpm run check:generated` in the
 * workspace root regenerates them and fails when the committed output is out
 * of date.
 *
 * `grammar/search-syntax.pegjs` is a byte-for-byte copy of the Sentry
 * frontend grammar at
 *   https://github.com/getsentry/sentry/blob/master/static/app/components/searchSyntax/grammar.pegjs
 * so the two can converge on one source.
 *
 * Usage:
 *   pnpm --filter @sentry/toolkit-core generate
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import peggy from "peggy";

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER =
  "// Auto-generated by packages/toolkit-core/script/generate-parsers.ts — DO NOT EDIT\n";

type GrammarSpec = {
  grammar: string;
  output: string;
  allowedStartRules: string[];
  declarations: string;
};

const GRAMMARS: GrammarSpec[] = [
  {
    grammar: "grammar/search-syntax.pegjs",
    output: "src/generated/search-syntax-grammar",
    allowedStartRules: ["search"],
    declarations: `${HEADER}
/**
 * Options the search grammar reads from \`options\`. The grammar builds every
 * token through \`TokenConverter\`, so callers decide the token shapes and the
 * key-type predicates. See \`../search-syntax.ts\` for the default converter.
 */
export type SearchGrammarOptions = {
  /** Constructed with \`{ text, location, config }\` once per parse. */
  TokenConverter: new (opts: never) => unknown;
  TermOperator: { DEFAULT: string };
  FilterType: Record<string, string>;
  config: unknown;
  startRule?: "search";
};

export declare class SyntaxError extends Error {
  expected: unknown;
  found: string | null;
  location: unknown;
}

/** Parse a search query. Throws {@link SyntaxError} when it does not match. */
export declare function parse(
  input: string,
  options: SearchGrammarOptions,
): unknown[];
`,
  },
];

for (const spec of GRAMMARS) {
  const grammarSource = await readFile(
    resolve(PACKAGE_ROOT, spec.grammar),
    "utf-8",
  );
  const parserSource = peggy.generate(grammarSource, {
    output: "source",
    format: "es",
    allowedStartRules: spec.allowedStartRules,
    grammarSource: spec.grammar,
  });

  const outputBase = resolve(PACKAGE_ROOT, spec.output);
  await mkdir(dirname(outputBase), { recursive: true });
  await writeFile(`${outputBase}.js`, `${HEADER}\n${parserSource}\n`);
  await writeFile(`${outputBase}.d.ts`, spec.declarations);
  console.log(`Generated ${spec.output}.js and ${spec.output}.d.ts`);
}
