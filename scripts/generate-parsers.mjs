#!/usr/bin/env node
/**
 * Compile the workspace PEG grammars into committed ES module parsers.
 *
 * Each parser is written next to its package's TypeScript source under
 * `src/generated/`, with a hand-written `.d.ts`, and committed: toolkit-core
 * has no build step, and the CLI imports its parser like any other module.
 * `pnpm run check:generated` regenerates them and fails when the committed
 * output is out of date; the pre-commit hook regenerates them for staged
 * grammar changes.
 *
 * `packages/toolkit-core/grammar/search-syntax.pegjs` is a byte-for-byte copy
 * of the Sentry frontend grammar at
 *   https://github.com/getsentry/sentry/blob/master/static/app/components/searchSyntax/grammar.pegjs
 * so the two can converge on one source.
 *
 * Usage:
 *   pnpm run generate:parsers
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import peggy from "peggy";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER =
  "// Auto-generated by scripts/generate-parsers.mjs — DO NOT EDIT\n";

const SYNTAX_ERROR_DECLARATION = `export declare class SyntaxError extends Error {
  expected: unknown;
  found: string | null;
  location: unknown;
}
`;

/**
 * @typedef {object} GrammarSpec
 * @property {string} grammar - Grammar path, relative to the workspace root
 * @property {string} output - Output path without extension
 * @property {string[]} allowedStartRules - Rules callers may start from
 * @property {string} declarations - Body of the generated `.d.ts`
 */

/** @type {GrammarSpec[]} */
const GRAMMARS = [
  {
    grammar: "packages/toolkit-core/grammar/search-syntax.pegjs",
    output: "packages/toolkit-core/src/generated/search-syntax-grammar",
    allowedStartRules: ["search"],
    declarations: `
/**
 * Options the search grammar reads from \`options\`. The grammar builds every
 * token through \`TokenConverter\`, so callers decide the token shapes and the
 * key-type predicates. See \`../search-syntax.ts\` for the default converter.
 */
export type SearchGrammarOptions = {
  /** Constructed with \`{ text, location, config }\` once per parse. */
  TokenConverter: new (opts: never) => unknown;
  TermOperator: { DEFAULT: string };
  FilterType: Record<string, string>;
  config: unknown;
  startRule?: "search";
};

${SYNTAX_ERROR_DECLARATION}
/** Parse a search query. Throws {@link SyntaxError} when it does not match. */
export declare function parse(
  input: string,
  options: SearchGrammarOptions,
): unknown[];
`,
  },
  {
    grammar: "packages/cli/grammar/org-project-target.pegjs",
    output: "packages/cli/src/generated/org-project-target-grammar",
    allowedStartRules: ["target"],
    declarations: `
import type { ParsedOrgProject } from "../lib/arg-parsing.js";

/**
 * Hooks the target grammar calls for character-level validation, so its
 * errors match the rest of the CLI. See \`parseOrgProjectArg()\`.
 */
export type OrgProjectTargetGrammarOptions = {
  /** Accept \`<org>/<project>,<project>\` lists. */
  multi?: boolean;
  /** Throw when \`value\` is not a valid slug. */
  checkSlug: (value: string, label: string) => void;
  /** Throw when \`value\` starts with \`@\`. */
  rejectAt: (value: string, label: string) => void;
  /** Throw a validation error. */
  invalid: (message: string, field?: string) => never;
  startRule?: "target";
};

${SYNTAX_ERROR_DECLARATION}
/** Parse a non-empty target that is not a URL. */
export declare function parse(
  input: string,
  options: OrgProjectTargetGrammarOptions,
): Exclude<ParsedOrgProject, { type: "auto-detect" }>;
`,
  },
];

for (const spec of GRAMMARS) {
  const grammarSource = await readFile(resolve(ROOT, spec.grammar), "utf-8");
  const parserSource = peggy.generate(grammarSource, {
    output: "source",
    format: "es",
    allowedStartRules: spec.allowedStartRules,
    grammarSource: spec.grammar,
  });

  const outputBase = resolve(ROOT, spec.output);
  await mkdir(dirname(outputBase), { recursive: true });
  await writeFile(`${outputBase}.js`, `${HEADER}\n${parserSource}\n`);
  await writeFile(`${outputBase}.d.ts`, `${HEADER}${spec.declarations}`);
  console.log(`Generated ${spec.output}.js and ${spec.output}.d.ts`);
}
