#!/usr/bin/env node
/**
 * Compile a package's PEG grammars into ES module parsers.
 *
 * Every `grammar/<name>.pegjs` in the package becomes
 * `src/generated/<name>-grammar.js`. Its types live in the hand-written
 * `grammar/<name>.d.ts` next to the grammar, a real TypeScript file that
 * editors and linters check in place. The generator copies it to
 * `src/generated/<name>-grammar.d.ts`. Relative module specifiers, found
 * with the TypeScript parser, are rebased so they resolve to the same
 * modules from there; nothing else in the file changes.
 *
 * The CLI generates its parsers at build time (`pnpm run generate:grammar`
 * in packages/cli).
 *
 * Usage:
 *   node scripts/generate-parsers.mjs <package-dir>
 */

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";
import peggy from "peggy";
import ts from "typescript";

const HEADER =
  "// Auto-generated by scripts/generate-parsers.mjs — DO NOT EDIT\n";

const packageDir = process.argv[2];
if (!packageDir) {
  console.error("Usage: node scripts/generate-parsers.mjs <package-dir>");
  process.exit(1);
}
const grammarDir = resolve(packageDir, "grammar");
const outputDir = resolve(packageDir, "src", "generated");

/** Point a relative specifier written from `grammarDir` at `outputDir`. */
function rebaseSpecifier(specifier) {
  if (!specifier.startsWith(".")) {
    return specifier;
  }
  const path = relative(outputDir, resolve(grammarDir, specifier))
    .split(sep)
    .join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

/** Module specifier literals of import/export declarations and `import()` types. */
function moduleSpecifiers(file) {
  const found = [];
  const visit = (node) => {
    const specifier =
      ts.isImportDeclaration(node) || ts.isExportDeclaration(node)
        ? node.moduleSpecifier
        : ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)
          ? node.argument.literal
          : undefined;
    if (specifier && ts.isStringLiteral(specifier)) {
      found.push(specifier);
    }
    ts.forEachChild(node, visit);
  };
  visit(file);
  return found;
}

/** Rebase every relative module specifier, located with the TypeScript parser. */
function rebaseDeclarations(source, fileName) {
  const file = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest);
  let result = source;
  // Splice from the end so earlier offsets stay valid. Each literal spans
  // its quotes; only the text between them is replaced.
  for (const literal of moduleSpecifiers(file).toReversed()) {
    const start = literal.getStart(file) + 1;
    const end = literal.end - 1;
    result =
      result.slice(0, start) +
      rebaseSpecifier(literal.text) +
      result.slice(end);
  }
  return result;
}

const grammars = (await readdir(grammarDir)).filter((file) =>
  file.endsWith(".pegjs"),
);
await mkdir(outputDir, { recursive: true });

for (const file of grammars) {
  const name = file.slice(0, -".pegjs".length);
  const grammarPath = join(grammarDir, file);
  const declarationsPath = join(grammarDir, `${name}.d.ts`);
  if (!existsSync(declarationsPath)) {
    throw new Error(`${declarationsPath} is missing`);
  }

  const parserSource = peggy.generate(await readFile(grammarPath, "utf-8"), {
    output: "source",
    format: "es",
    grammarSource: relative(packageDir, grammarPath).split(sep).join("/"),
  });
  const declarations = rebaseDeclarations(
    await readFile(declarationsPath, "utf-8"),
    declarationsPath,
  );

  const outputBase = join(outputDir, `${name}-grammar`);
  await writeFile(`${outputBase}.js`, `${HEADER}\n${parserSource}\n`);
  await writeFile(`${outputBase}.d.ts`, `${HEADER}\n${declarations}`);
  console.log(`Generated ${relative(process.cwd(), outputBase)}.{js,d.ts}`);
}
